PROMPT 3. Querying Semi-Structured JSON Data Using SQL Operators (JSON_VALUE)
PROMPT ==============================================================================

DECLARE
    v_risk_level VARCHAR2(50);
    v_ticker     VARCHAR2(50);
    v_price      NUMBER;
BEGIN
    -- Extract specific fields from the JSON document using JSON_VALUE
    SELECT JSON_VALUE(metadata, '$.risk_profile')
    INTO v_risk_level
    FROM client_portfolio_payloads
    WHERE customer_id = 1 AND document_type = 'INVESTMENT_PREFERENCES';

    DBMS_OUTPUT.PUT_LINE('Extracted Customer Risk Profile (JSON): ' || v_risk_level);

    -- Extract market feed details
    SELECT JSON_VALUE(metadata, '$.ticker'), JSON_VALUE(metadata, '$.current_price' RETURNING NUMBER)
    INTO v_ticker, v_price
    FROM client_portfolio_payloads
    WHERE document_type = 'MARKET_FEED_SNAPSHOT';

    DBMS_OUTPUT.PUT_LINE('Extracted Market Feed - Ticker: ' || v_ticker || ' | Price: NGN ' || v_price);
END;
/

