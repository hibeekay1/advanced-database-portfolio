PROMPT 1. Creating Semi-Structured JSON Storage Table for Market Feeds & Client Portfolios
PROMPT ==============================================================================

-- Create table using Oracle native JSON data type with conditional exception handling
BEGIN
    EXECUTE IMMEDIATE '
    CREATE TABLE client_portfolio_payloads (
        payload_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        customer_id     NUMBER NOT NULL,
        document_type   VARCHAR2(50) NOT NULL,
        metadata        JSON,
        created_at      TIMESTAMP DEFAULT SYSTIMESTAMP
    )';
    DBMS_OUTPUT.PUT_LINE('Table client_portfolio_payloads created successfully.');
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE = -00955 THEN
            DBMS_OUTPUT.PUT_LINE('Table client_portfolio_payloads already exists. Proceeding with existing table.');
        ELSE
            RAISE;
        END IF;
END;
/

