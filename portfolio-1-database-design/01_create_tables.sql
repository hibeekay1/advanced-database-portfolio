--------------------------------------------------------------------------------
-- IBUKUN INVESTMENT MANAGEMENT COMPANY - DATABASE SCHEMA (DDL)
--------------------------------------------------------------------------------

-- 1. Customer Detail Table
CREATE TABLE customers (
    customer_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name    VARCHAR2(50) NOT NULL,
    last_name     VARCHAR2(50) NOT NULL,
    account_type  VARCHAR2(30) CHECK (account_type IN ('Individual', 'Corporate', 'Joint')),
    email_address VARCHAR2(100) UNIQUE NOT NULL,
    phone_number  VARCHAR2(20),
    date_joined   DATE DEFAULT SYSDATE
);

-- 2. Wallet Table (Cash settlement account per customer)
CREATE TABLE wallets (
    wallet_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   NUMBER NOT NULL,
    currency      VARCHAR2(10) DEFAULT 'NGN',
    balance       NUMBER(15, 2) DEFAULT 0.00,
    CONSTRAINT fk_wallet_customer FOREIGN KEY (customer_id) REFERENCES customers(customer_id)
);

-- 3. Investment Products Catalog (Money Market, Fixed Deposits, Placements)
CREATE TABLE investment_products (
    product_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fund_description VARCHAR2(150) NOT NULL,
    product_type     VARCHAR2(30) CHECK (product_type IN ('Money Market', 'Mutual Fund', 'Fixed Deposit', 'Placement')),
    interest_rate    NUMBER(5, 2), -- e.g. 18.50%
    min_amount       NUMBER(12, 2) NOT NULL
);

-- 4. Client Investment Holdings (Tracks active investments held by clients)
CREATE TABLE client_investments (
    investment_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     NUMBER NOT NULL,
    product_id      NUMBER NOT NULL,
    invested_amount NUMBER(15, 2) NOT NULL,
    current_value   NUMBER(15, 2) NOT NULL,
    start_date      DATE DEFAULT SYSDATE,
    maturity_date   DATE,
    CONSTRAINT fk_inv_customer FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
    CONSTRAINT fk_inv_product FOREIGN KEY (product_id) REFERENCES investment_products(product_id)
);

-- 5. Transaction Ledger (Tracks cash movements, subscriptions & redemptions)
CREATE TABLE transactions (
    transaction_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    NUMBER NOT NULL,
    product_id     NUMBER NOT NULL,
    txn_type       VARCHAR2(20) CHECK (txn_type IN ('SUBSCRIPTION', 'REDEMPTION', 'INTEREST_PAYOUT')),
    amount         NUMBER(15, 2) NOT NULL,
    txn_timestamp  TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT fk_txn_customer FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
    CONSTRAINT fk_txn_product FOREIGN KEY (product_id) REFERENCES investment_products(product_id)
);